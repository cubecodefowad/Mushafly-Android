#!/usr/bin/env node
/**
 * Turns the Quranic signs in `text-marks.ts` into vector outlines.
 *
 * Most of these signs (U+06D6–U+06DC, U+06DF, U+06E0, U+06E2) are combining
 * marks with zero advance width. Rendered on their own in a React Native Text,
 * Android measures them as zero-width and the ink is clipped or dropped, which
 * is why the Tajweed reference showed empty boxes. Drawing the font's own
 * outline with react-native-svg removes the text shaper from the path: the ink
 * is always visible and always centred in its key cell.
 *
 * The script reads the bundled Amiri Quran font, so the outlines are the same
 * shapes the reader draws, not hand-drawn approximations.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { ORTHOGRAPHIC_MARKS, TEXT_MARKS } from "../src/features/quran/text-marks.ts";

const fontkit = createRequire(import.meta.url)("fontkit");

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const fontPath = resolve(root, "assets", "fonts", "AmiriQuran-Regular.ttf");
const outputPath = resolve(root, "src", "data", "generated", "mark-glyphs.ts");

function fail(message) {
  console.error(`generate-mark-glyphs: ${message}`);
  process.exit(1);
}

const font = fontkit.openSync(fontPath);
const unitsPerEm = font.unitsPerEm;

const glyphs = [
  ...TEXT_MARKS.map((mark) => mark.glyph),
  ...ORTHOGRAPHIC_MARKS.flatMap((mark) => mark.glyphs.map((part) => part.glyph)),
];

const unique = [...new Set(glyphs)];
const entries = [];
const seen = new Set();

for (const glyph of unique) {
  const codepoint = glyph.codePointAt(0);
  if (codepoint === undefined) fail(`cannot read the code point of ${JSON.stringify(glyph)}`);
  if (seen.has(codepoint)) continue;
  seen.add(codepoint);

  const fontGlyph = font.glyphForCodePoint(codepoint);
  if (!fontGlyph || fontGlyph.id === 0) {
    fail(`the bundled font has no glyph for U+${codepoint.toString(16).toUpperCase()}`);
  }
  const path = fontGlyph.path.toSVG();
  if (!path || !path.startsWith("M")) {
    fail(`U+${codepoint.toString(16).toUpperCase()} produced no outline`);
  }

  const { minX, minY, maxX, maxY } = fontGlyph.bbox;
  const width = maxX - minX;
  const height = maxY - minY;
  if (!(width > 0) || !(height > 0)) {
    fail(`U+${codepoint.toString(16).toUpperCase()} has an empty bounding box`);
  }

  // A little padding keeps antialiased edges inside the viewport.
  const padX = Math.max(12, width * 0.04);
  const padY = Math.max(12, height * 0.04);
  const round = (value) => Math.round(value * 100) / 100;

  entries.push({
    codepoint,
    path,
    minX: round(minX - padX),
    minY: round(minY - padY),
    maxX: round(maxX + padX),
    maxY: round(maxY + padY),
  });
}

// The units-per-em is embedded in each entry so the renderer never has to
// assume a font size.
const records = entries
  .map(
    (entry) => `  0x${entry.codepoint.toString(16).padStart(4, "0")}: {
    path: ${JSON.stringify(entry.path)},
    minX: ${entry.minX},
    minY: ${entry.minY},
    maxX: ${entry.maxX},
    maxY: ${entry.maxY},
    unitsPerEm: ${unitsPerEm},
  },`,
  )
  .join("\n");

const output = `// Generated by scripts/generate-mark-glyphs.mjs. Do not edit by hand.
// Outlines come from the bundled Amiri Quran font; see text-marks.ts for the
// signs they draw. Vector paths keep the signs visible on Android, where a
// zero-advance combining mark in a Text can be measured as empty.
import type { MarkGlyphData } from "../../types/quran";

export const MARK_GLYPHS: Record<number, MarkGlyphData> = {
${records}
};
`;

writeFileSync(outputPath, output, "utf8");
console.log(
  `generate-mark-glyphs: wrote ${entries.length} outlines for ${unitsPerEm} units per em to src/data/generated/mark-glyphs.ts`,
);
