#!/usr/bin/env node
/**
 * Copies the website's audited recitation catalogue into the app.
 *
 * `src/data/generated/reciters.json` is produced by the website's
 * `scripts/audit-reciters.mjs`, which checks every everyayah.com folder for
 * all 6,236 ayah files. That audit needs the network, so the app does not
 * repeat it: it consumes the same manifest and the same stable reciter ids.
 *
 * The manifest is committed as a TypeScript module so the bundle carries it
 * without a JSON import flag, and so a broken manifest fails the build.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const mobileRoot = resolve(here, "..");
const manifestPath = resolve(mobileRoot, "..", "src", "data", "generated", "reciters.json");
const outputPath = resolve(mobileRoot, "src", "data", "generated", "reciters.ts");

function fail(message) {
  console.error(`sync-reciters: ${message}`);
  process.exit(1);
}

let manifest;
try {
  manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
} catch (error) {
  fail(`cannot read ${manifestPath}: ${error instanceof Error ? error.message : error}`);
}

if (!Array.isArray(manifest.reciters) || manifest.reciters.length === 0) {
  fail("the manifest has no reciters");
}
if (!Array.isArray(manifest.excluded)) {
  fail("the manifest has no exclusion list");
}

const ids = new Set();
for (const reciter of manifest.reciters) {
  for (const field of ["id", "name", "folder", "kind", "language"]) {
    if (typeof reciter[field] !== "string" || reciter[field].length === 0) {
      fail(`reciter ${JSON.stringify(reciter)} is missing ${field}`);
    }
  }
  if (!["hafs", "warsh", "translation"].includes(reciter.kind)) {
    fail(`reciter ${reciter.id} has an unknown kind ${reciter.kind}`);
  }
  if (reciter.bitrate !== null && !Number.isInteger(reciter.bitrate)) {
    fail(`reciter ${reciter.id} has a non-integer bitrate`);
  }
  if (typeof reciter.bismillah !== "boolean") {
    fail(`reciter ${reciter.id} has no bismillah flag`);
  }
  if (ids.has(reciter.id)) fail(`duplicate reciter id ${reciter.id}`);
  ids.add(reciter.id);
}

if (manifest.counts?.offered !== manifest.reciters.length) {
  fail(
    `manifest counts ${manifest.counts?.offered ?? "?"} offered but lists ${manifest.reciters.length}`,
  );
}

const header = `// Generated by scripts/sync-reciters.mjs. Do not edit by hand.
// Source: the website's audited src/data/generated/reciters.json.
import type { ReciterManifest } from "../../types/quran";

export const RECITER_MANIFEST: ReciterManifest = `;

writeFileSync(outputPath, `${header}${JSON.stringify(manifest, null, 2)};\n`, "utf8");

console.log(
  `sync-reciters: wrote ${manifest.reciters.length} reciters and ${manifest.excluded.length} exclusions to src/data/generated/reciters.ts`,
);
